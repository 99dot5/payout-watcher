//! The vault's fast-payout protocol, shared by everything that signs or checks
//! one (`docs/specs/session-payout-ledger.md` D3; ADR 0027 §4.2).
//!
//! `crypto/vault-contract`'s `fast_payout` pays a session's owner when two of
//! the vault's four `payout_signers` have signed
//!
//! ```text
//! PACK(("fast-payout:v1", chain_id, vault, session_id, amount))
//! ```
//!
//! This crate is the one Rust producer of those bytes ([`fast_payout_payload`])
//! and of the secp256k1 signature the two online signers put over them
//! ([`sign::sign_fast_payout`]), plus the verifier a watcher or the submitting
//! worker checks a signature with ([`verify_fast_payout_signature`]). The
//! sequencer's signer, the validator (`services/validator`, ADR 0028 §4.3),
//! the operator CLI and ADR 0027's watcher all take it from here, so none of
//! them carries its own encoder.
//!
//! Every byte is pinned to `tools/operator-cli/tests/fast-payout-vectors.json`
//! (generated by `local-env/admin-ops/gen_fast_payout_vectors.py` with
//! pytezos; the vault's own `sp.pack` and the octez node agree on the same
//! file): the payload for the fixture's inputs, and — because [`sign`] is RFC
//! 6979 deterministic — the exact signature the fixture's secp256k1 signers
//! produced from their secret exponents.
//!
//! Two more things live here because both *checkers* of a fast payout read
//! them identically, the validator before it signs and the public watcher
//! (`tools/payout-watcher`) after the payout landed: the kernel's identity
//! ([`kernel_identity`]: the reveal-tree root hash of the installed kernel,
//! ADR 0027 §1.3 condition 2) and the durable keys of the session and
//! `session-{session_id}-end-payout` records the amount is read from
//! ([`kernel_records`]).
//!
//! The vault's L1 footprint is read here too, because every checker reads it
//! the same way: [`micheline`] reads a node's Micheline JSON by field
//! annotation, [`keys`] normalises the keys, signatures and addresses in it,
//! and [`events`] decodes one block's `fast_payout`, `cemented_payout` and
//! `sweep` events of a vault, each paired with the call that carried it. The
//! public watcher reads a block through it after the fact; the operator's
//! sweep tracker reads the same block the same way to confirm a sweep
//! reached the treasury.
//!
//! This crate is published with the watcher, so it holds the protocol only.
//! How the operator runs its signers (the production key backend and the
//! orchestration between them) lives in a crate of its own.
//!
//! Deliberately NOT here: the signer-rotation payload
//! (`fast-payout-rotate:v1`), which needs a key-ordered `set key` and lives
//! with the ceremony in the operator CLI (`payout_signers.rs`); and any notion
//! of *which* amount to sign — the validator decides that from its own rollup
//! node, never from a request (ADR 0028 §4.5).
//!
//! The same vault verifies one more signature from the sequencer under the
//! same rule: the **deposit authorisation** (ADR 0027 §4.4), the backend's
//! signature that admits a registered wallet's deposit, over its own
//! six-tuple PACK domain (`deposit_authorisation`). It shares the encoder
//! conventions, the signer trait and the one hashing path (`sign_payload`).

