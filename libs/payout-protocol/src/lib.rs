/// Verify that `signature` is `public_key`'s signature over a fast-payout
/// `payload` — the check the vault's `CHECK_SIGNATURE` makes, for a watcher
/// reading a `fast_payout` operation off L1 or a worker checking what a
/// co-signer returned before it submits.
///
/// Ed25519, secp256k1 and P-256 keys, in the key's own signature form or the
/// generic `sig…`; a curve-specific signature on another curve's key is
/// refused before any arithmetic. BLS signers are not verifiable here (the
/// operator CLI's `possession.rs` carries that arm for ceremonies).
pub fn verify_fast_payout_signature(
    public_key: &str,
    signature: &str,
    payload: &[u8],
) -> Result<(), WalletSignatureError> {
    tezos_wallet_signature::verify_over(public_key, signature, payload)
}
